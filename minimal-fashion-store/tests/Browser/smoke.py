from playwright.sync_api import sync_playwright, expect
import json, time, os, base64
from pathlib import Path
assert os.environ.get('QA_CONFIRM_DEMO') == 'yes', 'Run only on a disposable seeded demo; set QA_CONFIRM_DEMO=yes'
base = os.environ.get('STORE_BASE_URL', 'http://localhost:8000').rstrip('/')
out = Path(os.environ.get('QA_OUTPUT', '/tmp/minimal-browser-qa'))
out.mkdir(parents=True, exist_ok=True)
fixture = out / 'upload.png'
fixture.write_bytes(base64.b64decode('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII='))
collection_name = 'Bộ sưu tập QA ' + str(int(time.time()))
collection_slug = 'qa-collection-' + str(int(time.time()))
return_reason = 'QA: Không vừa kích thước ' + str(int(time.time()))
report = {'checks': [], 'page_errors': []}
with sync_playwright() as p:
    browser = p.chromium.launch(executable_path=os.environ.get('CHROMIUM_PATH') or None, headless=True, args=['--no-sandbox', '--disable-dev-shm-usage'])
    page = browser.new_page(viewport={'width': 1440, 'height': 1000}, device_scale_factor=1)
    page.on('pageerror', lambda e: report['page_errors'].append(str(e)))
    page.goto(base + '/', wait_until='networkidle')
    page.locator('.editorial').scroll_into_view_if_needed()
    page.wait_for_timeout(200)
    page.evaluate('window.scrollTo(0,0)')
    page.screenshot(path=str(out / 'home-desktop.png'), full_page=True)
    assert page.locator('h1').inner_text() == 'Đơn giản. Là chính bạn.'
    report['checks'].append('Homepage desktop rendered')
    page.goto(base + '/login')
    page.locator('#email').fill('customer1@example.test')
    page.locator('#password').fill('DemoFashion123!')
    page.get_by_role('button', name='Đăng nhập', exact=True).click()
    page.wait_for_url('**/account')
    report['checks'].append('Customer login with real session and CSRF form')
    page.goto(base + '/products/1')
    page.select_option('#size', 'M')
    page.select_option('#color', 'Đen')
    assert 'Còn' in page.locator('[aria-live="polite"]').last.inner_text()
    page.get_by_role('button', name='Thêm vào giỏ hàng').click()
    page.wait_for_url('**/cart')
    page.get_by_role('link', name='Tiến hành đặt hàng').click()
    page.wait_for_url('**/checkout**')
    page.locator('input[name="shipping_method"][value="express"]').check()
    page.get_by_role('button', name='Xác nhận đặt hàng').click()
    page.wait_for_url('**/orders/*')
    order_url = page.url
    assert page.get_by_text('Giao hàng nhanh', exact=True).is_visible()
    assert page.get_by_text('Đặt hàng thành công.').is_visible()
    report['checks'].append('Variant selection → cart → COD checkout → persisted order')
    page.reload()
    assert page.get_by_text('Cảm ơn bạn đã lựa chọn.').is_visible()
    report['checks'].append('Order persists after reload')
    csrf = page.request.post(base + '/cart/items', data={'product_variant_id': 1, 'quantity': 1})
    assert csrf.status == 419
    report['checks'].append('POST without CSRF rejected with 419')
    page.goto(base + '/account')
    page.get_by_role('button', name='Đăng xuất', exact=True).click()
    page.goto(base + '/login')
    page.locator('#email').fill('admin@example.test')
    page.locator('#password').fill('DemoFashion123!')
    page.get_by_role('button', name='Đăng nhập', exact=True).click()
    page.wait_for_url('**/account')
    page.goto(base + '/manage', wait_until='networkidle')
    assert page.locator('#revenue-chart').count() == 1
    page.screenshot(path=str(out / 'dashboard-desktop.png'), full_page=True)
    report['checks'].append('Admin dashboard and Chart.js rendered')
    for route in ['/admin', '/manage/products', '/manage/products/1/edit', '/manage/orders', '/manage/inventory', '/manage/returns', '/admin/payments', '/admin/vouchers', '/admin/vouchers/create', '/admin/collections', '/admin/collections/create', '/admin/shipping', '/collections']:
        response = page.goto(base + '' + route, wait_until='networkidle')
        assert response.status == 200, (route, response.status)
        report['checks'].append(route + ' HTTP 200')
    page.goto(base + '/manage/orders')
    page.locator('table a').first.click()
    page.on('dialog', lambda d: d.accept())
    for state in ['confirmed', 'packing', 'shipping', 'delivered', 'completed']:
        page.select_option('#status', state)
        page.get_by_role('button', name='Cập nhật trạng thái', exact=True).click()
        page.wait_for_load_state('networkidle')
    page.select_option('#type', 'capture')
    page.locator('#reference').fill('BROWSER-QA-COD-' + str(int(time.time())))
    page.locator('input[name="confirmed"]').check()
    page.get_by_role('button', name='Ghi nhận', exact=True).click()
    page.wait_for_load_state('networkidle')
    assert page.get_by_text('Đã ghi nhận giao dịch thực tế vào sổ thu/hoàn.').is_visible()
    report['checks'].append('Admin advances COD order through delivery/completion and records actual-demo collection')
    page.goto(base + '/admin/collections/create')
    page.locator('#name').fill(collection_name)
    page.locator('#slug').fill(collection_slug)
    page.locator('#description').fill('Kiểm tra lưu bộ sưu tập và ảnh')
    page.locator('#image').set_input_files(str(fixture))
    page.get_by_role('button', name='Lưu bộ sưu tập').click()
    page.wait_for_url('**/admin/collections')
    page.goto(base + '/collections')
    expect(page.get_by_text(collection_name, exact=True)).to_be_visible()
    report['checks'].append('Collection create with validated image upload persists on public listing')
    page.goto(base + '/account')
    page.get_by_role('button', name='Đăng xuất', exact=True).click()
    page.goto(base + '/login')
    page.locator('#email').fill('customer1@example.test')
    page.locator('#password').fill('DemoFashion123!')
    page.get_by_role('button', name='Đăng nhập', exact=True).click()
    page.wait_for_url('**/account')
    page.goto(order_url)
    page.get_by_text('Gửi yêu cầu đổi/trả', exact=True).click()
    page.locator('input[name="reason"]').fill(return_reason)
    page.get_by_role('button', name='Gửi yêu cầu', exact=True).click()
    page.wait_for_load_state('networkidle')
    expect(page.get_by_text('Đã gửi yêu cầu.', exact=False)).to_be_visible()
    report['checks'].append('Buyer submits return for delivered item')
    page.goto(base + '/account')
    page.get_by_role('button', name='Đăng xuất', exact=True).click()
    page.goto(base + '/login')
    page.locator('#email').fill('admin@example.test')
    page.locator('#password').fill('DemoFashion123!')
    page.get_by_role('button', name='Đăng nhập', exact=True).click()
    page.wait_for_url('**/account')
    page.goto(base + '/manage/returns')
    for state in ['approved', 'received']:
        panel = page.locator('section.panel').filter(has_text=return_reason)
        panel.locator('select[name="status"]').select_option(state)
        panel.locator('input[name="response"]').fill('QA: Đã kiểm tra hàng')
        panel.get_by_role('button', name='Cập nhật', exact=True).click()
        page.wait_for_load_state('networkidle')
    panel = page.locator('section.panel').filter(has_text=return_reason)
    panel.locator('input[name="confirmed"]').check()
    panel.get_by_role('button', name='Nhập lại kho', exact=False).click()
    page.wait_for_load_state('networkidle')
    expect(page.locator('section.panel').filter(has_text=return_reason).get_by_text('Đã nhập lại kho lúc', exact=False)).to_be_visible()
    report['checks'].append('Admin approves, receives and restocks return once')
    mobile = browser.new_page(viewport={'width': 390, 'height': 844}, device_scale_factor=1, is_mobile=True, has_touch=True)
    mobile.on('pageerror', lambda e: report['page_errors'].append(str(e)))
    mobile.goto(base + '/', wait_until='networkidle')
    mobile.locator('.editorial').scroll_into_view_if_needed()
    mobile.wait_for_timeout(200)
    mobile.evaluate('window.scrollTo(0,0)')
    mobile.screenshot(path=str(out / 'home-mobile.png'), full_page=True)
    assert mobile.evaluate('document.documentElement.scrollWidth <= window.innerWidth')
    mobile.get_by_role('button', name='Mở menu').click()
    expect(mobile.locator('.mobile-menu')).to_be_visible()
    report['checks'].append('390px mobile layout has no horizontal overflow; menu toggles')
    browser.close()
(out / 'browser-report.json').write_text(json.dumps(report, ensure_ascii=False, indent=2))
